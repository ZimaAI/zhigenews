#!/usr/bin/env node
/** Generate frontend types from the active backend API contract. */
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = 'backend/src/zhigenews/contracts/openapi.json';
const target = resolve(root, 'packages/api-client/src/generated.ts');
const raw = await readFile(resolve(root, source), 'utf8');
const contract = JSON.parse(raw);
const hash = createHash('sha256').update(raw).digest('hex');
const quote = (value) => JSON.stringify(value);

function typeOf(schema = {}) {
  if (schema === true) return 'unknown';
  if (schema === false) return 'never';
  if (schema.$ref) {
    const prefix = '#/components/schemas/';
    if (!schema.$ref.startsWith(prefix)) throw new Error(`Unsupported schema reference ${schema.$ref}`);
    return schema.$ref.slice(prefix.length);
  }
  if ('const' in schema) return quote(schema.const);
  if (schema.enum) return schema.enum.map(quote).join(' | ') || 'never';
  const { allOf, anyOf, oneOf, ...base } = schema;
  if (allOf || anyOf || oneOf) {
    const parent = typeOf(base);
    const alternatives = allOf || anyOf || oneOf;
    const combined = alternatives.map((item) => `(${typeOf(item)})`).join(allOf ? ' & ' : ' | ');
    return parent === 'unknown' ? `(${combined})` : `(${parent}) & (${combined})`;
  }
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => typeOf({ ...schema, type })).join(' | ');
  }
  switch (schema.type) {
    case 'null': return 'null';
    case 'string': return 'string';
    case 'number': case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return `Array<${typeOf(schema.items)}>`;
    default: {
      if (schema.type !== 'object' && !schema.properties && !schema.additionalProperties) return 'unknown';
      const required = new Set(schema.required || []);
      const properties = Object.entries(schema.properties || {}).map(([key, value]) => {
        const description = value.description ? `/** ${value.description.replaceAll('*/', '* /')} */\n` : '';
        return `${description}${quote(key)}${required.has(key) ? '' : '?'}: ${typeOf(value)};`;
      });
      if (schema.additionalProperties !== false) {
        properties.push(`[key: string]: ${typeOf(schema.additionalProperties || {})};`);
      }
      return `{\n${properties.map((line) => line.split('\n').map((part) => `  ${part}`).join('\n')).join('\n')}\n}`;
    }
  }
}

const metadata = {};
const requestTypes = [];
const responseTypes = [];
for (const [path, item] of Object.entries(contract.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!operation.operationId) continue;
    const name = operation.operationId;
    if (metadata[name]) throw new Error(`Duplicate operationId: ${name}`);
    const parameters = [...(item.parameters || []), ...(operation.parameters || [])];
    const success = Object.entries(operation.responses).filter(([status]) => /^2\d\d$/.test(status));
    const stream = success.some(([, response]) => response.content?.['text/event-stream']);
    metadata[name] = {
      method: method.toUpperCase(), path,
      role: operation['x-required-role'] || null,
      idempotencyRequired: parameters.some((p) => p.in === 'header' && p.name === 'Idempotency-Key' && p.required),
      pathParameters: parameters.filter((p) => p.in === 'path').map((p) => p.name),
      queryParameters: parameters.filter((p) => p.in === 'query').map((p) => p.name),
      bodyRequired: operation.requestBody?.required || false,
      successStatuses: success.map(([status]) => Number(status)),
      stream,
    };
    requestTypes.push(`  ${quote(name)}: ${operation.requestBody ? typeOf(operation.requestBody.content['application/json'].schema) : 'undefined'};`);
    responseTypes.push(`  ${quote(name)}: ${success.map(([, response]) => response.content?.['application/json'] ? typeOf(response.content['application/json'].schema) : stream ? 'RunEvent' : 'undefined').join(' | ')};`);
  }
}
const schemas = Object.entries(contract.components.schemas);
const output = `// Generated by scripts/frontend/generate-contract.mjs. Do not edit.\n// Source: ${source}\n// SHA-256: ${hash}\n// Structural TypeScript types; input lengths/ranges and cross-field constraints remain server-validated.\n\n${schemas.map(([name, schema]) => `export type ${name} = ${typeOf(schema)};`).join('\n\n')}\n\nexport type components = {\n  schemas: {\n${schemas.map(([name]) => `    ${quote(name)}: ${name};`).join('\n')}\n  };\n};\n\nexport const contractSource = ${quote(source)};\nexport const contractSha256 = ${quote(hash)};\nexport const operationMetadata = ${JSON.stringify(metadata, null, 2)} as const;\nexport type OperationId = keyof typeof operationMetadata;\nexport type OperationRequests = {\n${requestTypes.join('\n')}\n};\nexport type OperationResponses = {\n${responseTypes.join('\n')}\n};\n`;

if (process.argv.includes('--check')) {
  let actual = '';
  try { actual = await readFile(target, 'utf8'); } catch { /* Missing generated file is stale. */ }
  if (actual !== output) {
    console.error('Generated frontend contract is stale. Run node scripts/frontend/generate-contract.mjs.');
    process.exitCode = 1;
  } else console.log(`Contract current: ${schemas.length} schemas, ${Object.keys(metadata).length} operations, ${hash}`);
} else {
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, output, 'utf8');
  console.log(`Generated ${schemas.length} schemas and ${Object.keys(metadata).length} operations.`);
}
